#!/usr/bin/env python3
"""Regenerate the embedded PNG/JPEG samples used by standalone/apitest.c.

The image tests must not depend on files shipped next to the DLL, so the
two samples live in the test source as byte arrays. This script is how
they were produced; re-run it to change them.

    python tools/make_image_samples.py

Both samples are 16x16 so pdf_image_get_size() has something exact to
assert. The PNG is written by hand (zlib is in the stdlib) so the sample
does not depend on Pillow being installed; the JPEG needs Pillow because
a baseline JPEG is not something to hand-roll.
"""
import io
import struct
import sys
import zlib

W = H = 16


def pixels():
    """A pattern with distinct R/G/B regions so the image is not trivial."""
    rows = []
    for y in range(H):
        row = bytearray()
        for x in range(W):
            if x < W // 2 and y < H // 2:
                row += bytes((220, 40, 40))
            elif x >= W // 2 and y < H // 2:
                row += bytes((40, 180, 60))
            elif x < W // 2:
                row += bytes((50, 90, 220))
            else:
                row += bytes((240, 200, 40))
        rows.append(bytes(row))
    return rows


def make_png():
    raw = b"".join(b"\x00" + r for r in pixels())

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)  # 8-bit RGB
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def make_jpeg():
    try:
        from PIL import Image
    except ImportError:
        return None
    img = Image.new("RGB", (W, H))
    img.putdata([tuple(r[i:i + 3]) for r in pixels() for i in range(0, len(r), 3)])
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=70, optimize=True)
    return buf.getvalue()


def emit(name, blob):
    print("static const unsigned char %s[] = {" % name)
    for i in range(0, len(blob), 12):
        row = ", ".join("0x%02x" % b for b in blob[i:i + 12])
        print("    %s," % row)
    print("};")
    print("#define %s_LEN %d" % (name.upper(), len(blob)))
    print("/* %s: %d bytes */" % (name, len(blob)))
    print()


def main():
    png = make_png()
    jpeg = make_jpeg()
    if jpeg is None:
        print("Pillow not available - cannot regenerate the JPEG sample",
              file=sys.stderr)
        return 1
    print("/* generated by tools/make_image_samples.py - do not edit */")
    emit("sample_png", png)
    emit("sample_jpeg", jpeg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
