#include "pdflib/pdf_api.h"

#include <stdio.h>
#include <string.h>

/*
 * streamed_pdf - generate a PDF that MUST be produced through the
 * incremental (streaming) writer: pages are pushed to the output as they
 * complete and the total page count is never held in memory.
 *
 * Streaming creation is mandatory here, so the example refuses to fall
 * back to the buffered API. libharu (and the dummy marker backend) have
 * no streamed writer and report PDF_ERR_BACKEND_UNSUPPORTED; when that
 * happens this example automatically switches to PoDoFo, which streams
 * natively. If PoDoFo is not compiled in either, the example fails.
 *
 *   streamed_pdf <out.pdf> [podofo|libharu|dummy]
 *
 * With no backend argument the default (PDF_BACKEND_AUTO) is used. The
 * example prints the engine that actually produced the file, so passing
 * "libharu" demonstrates the automatic switch to PoDoFo.
 */

/* Collect a short summary of the streamed output as it is written. */
struct sink {
    unsigned long bytes;
    int chunks;
};

static pdf_status count_write(const unsigned char *data, size_t len, void *ud)
{
    struct sink *s = (struct sink *)ud;
    (void)data;
    if (len)
    {
        s->bytes += (unsigned long)len;
        s->chunks++;
    }
    return PDF_OK;
}

/* Draw one page. Called once per page while the document is streaming,
 * so nothing here depends on the final page count. */
static int draw_page(pdf_doc doc, int index)
{
    pdf_page page;
    pdf_font font;
    pdf_color accent;
    char title[128];

    if (pdf_page_add(doc, PDF_PAGE_A4, PDF_ORIENTATION_PORTRAIT, &page)
        != PDF_OK)
        return 1;

    if (pdf_font_get_std(doc, PDF_STD_FONT_HELVETICA, &font) != PDF_OK)
        return 2;

    accent.kind = PDF_COLOR_RGB;
    accent.c1 = 0.15;
    accent.c2 = 0.35;
    accent.c3 = 0.75;
    accent.c4 = 0;
    accent.alpha = 1;

    /* a band + the page label, streamed out with the page */
    pdf_set_fill_color(page, &accent);
    pdf_path_rectangle(page, &(pdf_rect){0, 742, 595.276, 100});
    pdf_path_paint(page, PDF_PATH_FILL);

    snprintf(title, sizeof(title), "Streamed page %d", index);
    pdf_page_draw_text(page, font, title, 48, 780, 24);

    pdf_set_stroke_color(page, &accent);
    pdf_set_line_width(page, 1.5);
    pdf_path_circle(page, 297.638, 420, 120);
    pdf_path_paint(page, PDF_PATH_STROKE);

    pdf_page_draw_text(page, font,
                       "generated by the incremental streaming writer",
                       48, 120, 12);
    return 0;
}

int main(int argc, char **argv)
{
    const char *out_path = argc > 1 ? argv[1] : "streamed.pdf";
    const char *want = argc > 2 ? argv[2] : NULL;
    const int pages = 6; /* "arrives" one page at a time */
    pdf_doc doc = NULL;
    pdf_status rc;
    int i;

    if (want)
    {
        if (strcmp(want, "podofo") == 0)
            pdflib_set_backend(PDF_BACKEND_PODOFO);
        else if (strcmp(want, "libharu") == 0)
            pdflib_set_backend(PDF_BACKEND_LIBHARU);
        else if (strcmp(want, "dummy") == 0)
            pdflib_set_backend(PDF_BACKEND_DUMMY);
        else
        {
            fprintf(stderr, "unknown backend '%s'\n", want);
            return 2;
        }
    }

    /* Streaming is required. Try it on the active backend first. */
    rc = pdf_doc_create_streamed_to_file(out_path, &doc);
    if (rc == PDF_ERR_BACKEND_UNSUPPORTED)
    {
        const char *unsupported = pdflib_backend_version();
        fprintf(stderr,
                "note: backend %s has no streamed writer; trying PoDoFo\n",
                unsupported ? unsupported : "(unknown)");

        if (!pdflib_has_backend(PDF_BACKEND_PODOFO))
        {
            fprintf(stderr,
                    "error: PoDoFo is not compiled in, cannot stream\n");
            return 1;
        }
        pdflib_set_backend(PDF_BACKEND_PODOFO);
        rc = pdf_doc_create_streamed_to_file(out_path, &doc);
    }

    if (rc != PDF_OK)
    {
        fprintf(stderr, "streamed create failed: %d (%s)\n", rc,
                pdflib_last_error(doc));
        return 1;
    }

    printf("streaming with %s\n", pdflib_backend_version());

    for (i = 1; i <= pages; i++)
    {
        int dr = draw_page(doc, i);
        if (dr != 0)
        {
            fprintf(stderr, "page %d failed (%d): %s\n", i, dr,
                    pdflib_last_error(doc));
            pdf_doc_free(doc); /* finish() implied; removes torn file */
            return 1;
        }
        /* the page has already been pushed to the sink here */
    }

    /* Required for streamed documents: embeds pending subsets and writes
     * the xref/trailer, completing the file. Idempotent. */
    if (pdf_doc_finish(doc) != PDF_OK)
    {
        fprintf(stderr, "finish failed: %s\n", pdflib_last_error(doc));
        pdf_doc_free(doc);
        return 1;
    }
    pdf_doc_free(doc);

    /* Report the file through the callback sink as an extra check that
     * the same document can also be streamed to a caller callback. */
    {
        struct sink s;
        pdf_doc sdoc = NULL;
        memset(&s, 0, sizeof(s));
        if (pdf_doc_create_streamed(count_write, &s, &sdoc) == PDF_OK)
        {
            draw_page(sdoc, 1);
            pdf_doc_finish(sdoc);
            pdf_doc_free(sdoc);
            printf("callback sink: %d chunk(s), %lu byte(s)\n",
                   s.chunks, s.bytes);
        }
    }

    printf("wrote %s (%d streamed pages, %s backend)\n", out_path, pages,
           pdflib_backend_version());
    return 0;
}
